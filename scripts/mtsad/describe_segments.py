"""Describe the labelled segment structure of each pinned benchmark payload.

The headline metric of this family credits a whole labelled segment once one of
its points is detected, so the number of segments - not the number of anomalous
points - decides how much a single lucky or unlucky detection moves the score.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from iia_benchmark.data.mtsad import load_dataset_config, load_mtsad_split  # noqa: E402
from iia_benchmark.evaluation.mtsad_metrics import anomaly_ranges  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--json-out", type=Path, default=None)
    args = parser.parse_args()
    rows = []
    for dataset in ("smd", "msl", "smap", "psm", "swat"):
        split = load_mtsad_split(dataset, root=ROOT / "data/public_datasets/mtsad")
        config = load_dataset_config(dataset, ROOT / "configs/datasets")
        ranges = anomaly_ranges(split.test_labels)
        lengths = np.array([end - start + 1 for start, end in ranges]) if ranges else np.zeros(0)
        ratio = float(config["anomaly_ratio"])
        max_pointwise_recall = min(1.0, (ratio / 100.0) / split.anomaly_rate) if split.anomaly_rate else 0.0
        rows.append(
            {
                "dataset": dataset.upper(),
                "test_points": int(len(split.test_labels)),
                "anomaly_rate": float(split.anomaly_rate),
                "segments": int(len(ranges)),
                "median_segment_length": float(np.median(lengths)) if len(lengths) else 0.0,
                "max_segment_length": int(lengths.max()) if len(lengths) else 0,
                "reference_anomaly_ratio_pct": ratio,
                "max_pointwise_recall_at_reference_threshold": float(max_pointwise_recall),
                "f1_weight_of_one_segment": float(
                    1.0 / len(ranges) if ranges else 0.0
                ),
            }
        )
    lines = [
        "# Labelled segment structure per payload",
        "",
        "Generated by `scripts/mtsad/describe_segments.py`. `max point-wise recall`",
        "is the recall ceiling implied purely by the alarm budget: the reference",
        "threshold flags the top `anomaly_ratio` percent of energies, so recall",
        "cannot exceed `ratio / anomaly_rate` no matter how good the model is.",
        "",
        "| Dataset | Test points | Anomaly rate | Segments | Median segment | Longest segment | Alarm budget | Max point-wise recall | Recall cost of one missed segment |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['dataset']} | {row['test_points']} | {row['anomaly_rate']:.4f} | "
            f"{row['segments']} | {row['median_segment_length']:.0f} | "
            f"{row['max_segment_length']} | {row['reference_anomaly_ratio_pct']:g}% | "
            f"{row['max_pointwise_recall_at_reference_threshold']:.4f} | "
            f"{row['f1_weight_of_one_segment']:.4f} |"
        )
    lines.append("")
    output = "\n".join(lines)
    print(output)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(output, encoding="utf-8")
        print(f"wrote {args.out}")
    if args.json_out:
        args.json_out.write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
